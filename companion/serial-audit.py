#!/usr/bin/env python3
"""UART observation; optional GCS heartbeat and read-only SERIAL2_PROTOCOL queries."""
import json
import os
import select
import termios
import time
import argparse
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--capture', type=Path, help='Optional file for received UART bytes')
parser.add_argument('--request-serial2-protocol', action='store_true',
                    help='Send GCS heartbeat and two read-only parameter queries to system/component 1/1')
args = parser.parse_args()
received = bytearray()

fd = os.open('/dev/serial0', (os.O_RDWR if args.request_serial2_protocol else os.O_RDONLY) |
             os.O_NOCTTY | os.O_NONBLOCK)
original = termios.tcgetattr(fd)
count = 0
sent = 0
try:
    attrs = termios.tcgetattr(fd)
    attrs[0] = attrs[1] = attrs[3] = 0
    attrs[2] = termios.CS8 | termios.CREAD | termios.CLOCAL
    attrs[4] = attrs[5] = termios.B115200
    attrs[6][termios.VMIN] = 0
    attrs[6][termios.VTIME] = 0
    termios.tcsetattr(fd, termios.TCSANOW, attrs)
    if args.request_serial2_protocol:
        # Generated by pymavlink v20 ardupilotmega; GCS source 255/190.
        # HEARTBEAT carries no vehicle commands. PARAM_REQUEST_READ is read-only.
        hello = bytes.fromhex('fd09000000ffbe0000000000000006080004033d48')
        request = bytes.fromhex('fd14000001ffbe140000ffff010153455249414c325f50524f544f434f4c8a57')
        time.sleep(0.25)
        sent += os.write(fd, hello)
        time.sleep(0.25)
        sent += os.write(fd, request)
        time.sleep(1)
        sent += os.write(fd, request)
    end = time.monotonic() + 8
    while time.monotonic() < end:
        ready, _, _ = select.select([fd], [], [], max(0, end-time.monotonic()))
        if ready:
            chunk = os.read(fd, 4096)
            count += len(chunk)
            if args.capture:
                received.extend(chunk)
finally:
    termios.tcsetattr(fd, termios.TCSANOW, original)
    os.close(fd)
if args.capture:
    args.capture.write_bytes(received)
print(json.dumps({'device': '/dev/serial0', 'baud': 115200, 'received_bytes': count,
                  'application_transmitted_bytes': sent, 'mavlink_validated': False}))
